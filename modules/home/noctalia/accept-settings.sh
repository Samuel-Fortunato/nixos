#!/usr/bin/env bash
set -euo pipefail

repo="${1:-/etc/nixos}"
dir="${repo%/}/modules/home/noctalia"
current="$dir/config.nix"
generated="$dir/config.generated.nix"

if [[ ! -f "$current" || ! -f "$generated" ]]; then
  printf 'Missing Noctalia configuration: %s or %s\n' "$current" "$generated" >&2
  exit 1
fi

if [[ -L "$current" || -L "$generated" ]]; then
  printf 'Refusing to operate on symlinked configuration files.\n' >&2
  exit 1
fi

if [[ "$(head -n 1 "$generated")" != '# Generated by noctalia-settings-export (Home Manager watcher)' ]]; then
  printf 'Unexpected generated file header: %s\n' "$generated" >&2
  exit 1
fi

# The first three lines of config.nix are its hand-maintained header.
for number in 1 2 3; do
  line="$(sed -n "${number}p" "$current")"
  if [[ "$line" != \#* ]]; then
    printf 'Expected a comment on line %s of %s\n' "$number" "$current" >&2
    exit 1
  fi
done

tmp="$(mktemp "$dir/.config-accept.XXXXXXXX.nix")"
trap 'rm -f -- "$tmp"' EXIT

{
  head -n 3 "$current"
  tail -n +4 "$generated"
} > "$tmp"

chmod --reference="$current" "$tmp"
nix-instantiate --parse "$tmp" > /dev/null

if cmp -s "$current" "$tmp"; then
  printf 'No changes to accept.\n'
  exit 0
fi

mv -f -- "$tmp" "$current"
trap - EXIT
printf 'Accepted Noctalia GUI snapshot into %s\n' "$current"
printf 'Review the Git diff, then run home-manager switch.\n'
